// Generates src/fusions-data.js: every duo (120) and trio (560) of the 16 base heroes, numbered 1…680.
// The numbering is FROZEN once published (art files and minted serials refer to these numbers) —
// new heroes' combinations must be appended after 680, never inserted.
const fs = require('fs'), path = require('path');
const ORDER = ['pinkbull', 'notcoin', 'volya', 'egor', 'paws', 'noctis', 'gramcat', 'utya', 'pengu', 'memegram', 'yoda', 'virus', 'babyshark', 'yaya', 'dog', 'teddy'];
// Hand-named combinations (others are named "A × B").
const NAMED = {
  'pinkbull+notcoin': ['Golden Bull', 'tank'], 'gramcat+utya': ['Sky Hunters', 'archer'], 'utya+pengu': ['Frost Twins', 'control'],
  'pengu+babyshark': ['Arctic Tide', 'healer'], 'egor+memegram': ['Crystal Star', 'mage'], 'paws+noctis': ['Shadow Paw', 'assassin'],
  'yoda+virus': ['Toxic Sage', 'mage'], 'yaya+teddy': ['Lantern Hug', 'support'], 'gramcat+dog': ['Courier Cat', 'archer'],
  'notcoin+volya': ['Legend Sentinel', 'tank'], 'pinkbull+teddy': ['Bull Market Boss', 'tank'], 'memegram+yoda': ['Cosmic Sage', 'mage'],
  'noctis+virus': ['Plague Shadow', 'assassin'], 'babyshark+yaya': ['Lantern Reef', 'healer'], 'egor+paws': ['Crystal Claw', 'warrior'],
  'volya+dog': ['Sky Courier', 'warrior'], 'pinkbull+notcoin+teddy': ['TON Treasury', 'tank'], 'utya+pengu+babyshark': ['Frozen Ocean', 'control'],
  'paws+noctis+virus': ['Night Plague', 'assassin'], 'egor+memegram+yoda': ['Crystal Cosmos', 'mage'], 'volya+gramcat+dog': ['Legend Express', 'warrior'],
  'babyshark+yaya+teddy': ['Lantern Festival', 'support'],
};
const LEGACY = { 'pinkbull+notcoin': 'f_golden_bull', 'gramcat+utya': 'f_sky_hunters', 'utya+pengu': 'f_frost_twins', 'pengu+babyshark': 'f_arctic_tide',
  'egor+memegram': 'f_crystal_star', 'paws+noctis': 'f_shadow_paw', 'yoda+virus': 'f_toxic_sage', 'yaya+teddy': 'f_lantern_hug', 'gramcat+dog': 'f_courier_cat',
  'notcoin+volya': 'f_legend_sentinel', 'pinkbull+teddy': 'f_bull_market', 'memegram+yoda': 'f_cosmic_sage', 'noctis+virus': 'f_plague_shadow',
  'babyshark+yaya': 'f_lantern_reef', 'egor+paws': 'f_crystal_claw', 'volya+dog': 'f_sky_courier', 'pinkbull+notcoin+teddy': 'f_ton_treasury',
  'utya+pengu+babyshark': 'f_frozen_ocean', 'paws+noctis+virus': 'f_night_plague', 'egor+memegram+yoda': 'f_crystal_cosmos',
  'volya+gramcat+dog': 'f_legend_express', 'babyshark+yaya+teddy': 'f_lantern_festival' };
const rows = [], legacy = {};
let n = 0;
const add = parts => {
  n++;
  const key = parts.join('+'), named = NAMED[key];
  rows.push(named ? [n, parts, named[0], named[1]] : [n, parts]);
  if (LEGACY[key]) legacy[LEGACY[key]] = 'f' + n;
};
for (let i = 0; i < 16; i++) for (let j = i + 1; j < 16; j++) add([ORDER[i], ORDER[j]]);
for (let i = 0; i < 16; i++) for (let j = i + 1; j < 16; j++) for (let k = j + 1; k < 16; k++) add([ORDER[i], ORDER[j], ORDER[k]]);
const body = rows.map(r => '  ' + JSON.stringify(r)).join(',\n');
const out = `// GENERATED by tools/gen_fusions.js — fusion card #N = [N, parts, name?, role?]. Numbers are permanent.
(function (root) {
  const FUSION_DATA = [\n${body},\n  ];
  const LEGACY_FUSION_IDS = ${JSON.stringify(legacy)};
  if (typeof module !== 'undefined') module.exports = { FUSION_DATA, LEGACY_FUSION_IDS };
  else { root.FUSION_DATA = FUSION_DATA; root.LEGACY_FUSION_IDS = LEGACY_FUSION_IDS; }
})(typeof self !== 'undefined' ? self : this);
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'fusions-data.js'), out);
console.log('fusions:', n, 'named:', Object.keys(NAMED).length, 'legacy:', Object.keys(legacy).length);
