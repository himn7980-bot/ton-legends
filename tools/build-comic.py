"""Turns the comic pages (tools/comic-src/*.dc.html, made on the design canvas) into src/comic-data.js for the
in-game Book of Legends: each page's markup with the pictures pointed at the game's own art ({{img:id}}), its
styles scoped per page under .comic.cm-<lang><n> with cm- class names, per language (fa, en)."""
import json, pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
srcdir = root / "tools" / "comic-src"
BLOBS = {
    "3740c249ec5382c3c90c44b2b3183cb4": "babyshark", "055e09a75434a65679637bcbb5c8970a": "dog", "8632124117bdb1650cf5f4cab35bcdca": "egor",
    "6f1734c1e67080f15b8d44c34a8a45bc": "gramcat", "f3b0bc6762e1f15e30c2c52f400e9caf": "memegram", "adfd1be40b9eb8bfc32980fd2d3ecc63": "noctis",
    "b5bea88d27db8b4a2138d4610c329ef5": "notcoin", "37aa1b8baa5b9d04876eb1548e529956": "paws", "54efaef0493621f61937ba68289aeb08": "pengu",
    "75a86d6c98822bb010825bfce9059750": "pinkbull", "5625d8dd72befc888324cd8eb3b2c420": "teddy", "a146213d74ac6bf50a8ee1243f980239": "utya",
    "efd2fe7cb9f07fc42072f31aae4451ee": "virus", "de96ca7b04b1a7ba881057b7411fb98f": "volya", "0344aa8cbadb0af6dfa0024880f131d9": "yaya",
    "703a2bdfd1018cde5504c0ca476b1f7c": "yoda", "ced118ae3a3ce543fbfb740f4fe93f0f": "ui-chest-royal", "5dfc3b0a283a8df9ddad4e8a50bb6401": "ui-gem-icon",
}
CLASSES = ["pn", "dots", "cap", "bub", "dark", "t", "sfx", "shadowed", "tag", "vl", "mini", "feat", "strip", "down", "hero"]
PAGES = {"fa": ["Main", "Ch1", "Ch2", "Ch3", "Ch4", "Ch5", "End"], "en": ["Cover-en", "Ch1-en", "Ch2-en", "Ch3-en", "Ch4-en", "Ch5-en", "End-en"]}
cls_re = re.compile(r'class="([^"]*)"')
css_re = re.compile(r"\.(" + "|".join(CLASSES) + r")\b")

def page(name, scope):
    s = (srcdir / f"{name}.dc.html").read_text(encoding="utf-8")
    css = re.search(r"<style>(.*?)</style>", s, re.S).group(1)
    body = re.search(r"</helmet>(.*)</x-dc>", s, re.S).group(1).strip()
    body = re.sub(r'src="/_blob/([0-9a-f]{32})"', lambda m: 'src="{{img:%s}}"' % BLOBS[m.group(1)], body)
    body = cls_re.sub(lambda m: 'class="%s"' % " ".join("cm-" + c if c in CLASSES else c for c in m.group(1).split()), body)
    body = re.sub(r"min-height: \d+px; ", "", body, count=1)  # pages grow with their panels in the game
    rules = []
    for rule in css.split("}"):
        if "{" not in rule: continue
        sel, decl = rule.split("{", 1)
        sel = sel.strip()
        if sel in ("body", "a", "a:hover") or sel.startswith("a{") or sel.startswith("a:"): continue
        sel = ",".join(f".comic.{scope} " + css_re.sub(lambda m: ".cm-" + m.group(1), x.strip()) for x in sel.split(","))
        rules.append(sel + "{" + decl.strip() + "}")
    return {"html": body, "css": rules}

NL = "\n"
out = {}
css = []
for lang, names in PAGES.items():
    out[lang] = []
    for i, nm in enumerate(names):
        p = page(nm, f"cm-{lang}{i}")
        out[lang].append(p["html"])
        for r in p["css"]:
            if r not in css: css.append(r)
data = "// Generated by tools/build-comic.py from tools/comic-src — do not edit by hand.\n" \
       "// Book of Legends pages per language: [cover, chapter 1..5, post-credits]; CSS scoped per page under .comic.cm-<lang><n>.\n" \
       f"const COMIC = {json.dumps({'pages': out, 'css': NL.join(css)}, ensure_ascii=False)};\n"
(root / "src" / "comic-data.js").write_text(data, encoding="utf-8")
print("src/comic-data.js", round(len(data.encode()) / 1024), "KB,", len(css), "css rules")
